'use strict';

// Bundles catalogue.json and every SVG it lists into assets/icon-data.js, so
// the gallery works on GitHub Pages and when index.html is opened from disk.
// Run after adding or changing icons: node tools/build-site.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const catalogue = JSON.parse(fs.readFileSync(path.join(ROOT, 'catalogue.json'), 'utf8'));
const categoryIds = new Set(catalogue.categories.map(c => c.id));
const seen = new Set();

const icons = catalogue.icons.map(icon => {
  if (seen.has(icon.id)) throw new Error(`Duplicate icon id "${icon.id}"`);
  seen.add(icon.id);
  if (!categoryIds.has(icon.category)) throw new Error(`${icon.id}: unknown category "${icon.category}"`);
  const svg = readSvg(icon, icon.file);
  const monoSvg = icon.monoFile ? readSvg(icon, icon.monoFile) : null;
  return { ...icon, svg, monoSvg };
});

function readSvg(icon, relative) {
  const file = path.join(ROOT, relative);
  if (!fs.existsSync(file)) throw new Error(`${icon.id}: missing file ${relative}`);
  return fs.readFileSync(file, 'utf8').replace(/^<\?xml[^>]*>\s*/, '');
}

fs.mkdirSync(path.join(ROOT, 'assets'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'assets', 'icon-data.js'),
  `// Generated by tools/build-site.js. Do not edit by hand.\nwindow.ICON_LIBRARY = ${JSON.stringify({ ...catalogue, icons })};\n`);
console.log(`Bundled ${icons.length} icons into assets/icon-data.js`);
